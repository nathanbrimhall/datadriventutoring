import { chromium } from 'playwright';
import { createApp } from '../server.mjs';
import { mkdirSync } from 'node:fs';
import assert from 'node:assert/strict';

mkdirSync('test-results',{recursive:true});
const {server,store}=createApp({dataDir:':memory:'});
const at=new Date().toISOString();
for(const [id,name] of [['alex','Alex'],['sam','Sam']])store.db.prepare('INSERT INTO students VALUES(?,?,?,?,?)').run(id,name,id+'-student',id+'-parent',at);
const question=prompt=>store.putQuestion({prompt,topics:['Recovery'],courses:['Algebra I'],type:'short-response',difficulty:'easy',answer:'4',explanation:'Two plus two is four.'});
const weak=question('Find two plus two.'),boundary=question('Evaluate eight divided by two.'),pending=question('Simplify two times two.'),viewed=question('Find the square root of sixteen.'),unseen=question('Solve x + 1 = 5.');
function attempt(student,q,correct) {
  const ticket=crypto.randomUUID();
  store.db.prepare('INSERT INTO tickets(id,studentId,question,guided,used,createdAt) VALUES(?,?,?,0,1,?)').run(ticket,student,JSON.stringify(q),at);
  store.db.prepare('INSERT INTO attempts VALUES(?,?,?,?,?,?,?,?,?,?,?)').run(crypto.randomUUID(),ticket,student,null,q.id,JSON.stringify(q),'4',correct,30,0,at);
  store.db.prepare('INSERT OR IGNORE INTO seen VALUES(?,?)').run(student,q.id);
}
attempt('alex',weak,0);attempt('alex',weak,0);
for(let i=0;i<20;i++)attempt('alex',boundary,i<13?1:0);
attempt('alex',pending,null);
store.db.prepare('INSERT INTO seen VALUES(?,?)').run('alex',viewed.id);
attempt('sam',boundary,0);attempt('sam',weak,1);
await new Promise(r=>server.listen(0,'127.0.0.1',r));
const browser=await chromium.launch({headless:true,...(process.env.BROWSER_CHANNEL?{channel:process.env.BROWSER_CHANNEL}:{})});
const page=await browser.newPage({viewport:{width:1440,height:1100}}),errors=[];
page.on('pageerror',e=>errors.push(e.message));
try {
  await page.goto('http://localhost:'+server.address().port+'/#access='+store.bootstrapToken);
  await page.getByRole('button',{name:'Create assignment',exact:true}).first().click();
  const form=page.locator('#assignment-builder-form');
  await form.locator('[name=title]').fill('Focused recovery');
  await form.locator('[name=students][value=alex]').check();
  assert.equal(await form.locator('[name=mode][value=automatic]').isChecked(),true);
  await form.locator('.assignment-facet').filter({has:page.locator('[name=topics]')}).locator('summary').click();
  await form.locator('[name=topics][value=Recovery]').check();
  await form.locator('#builder-browser > summary').click();
  await form.locator('#browse-summary').filter({hasText:'5 matching questions'}).waitFor();
  const row=prompt=>form.locator('#builder-question-list .assignment-question').filter({hasText:prompt});
  assert.match(await row(weak.prompt).innerText(),/0% correct · 0\/2/);
  assert.match(await row(boundary.prompt).innerText(),/65% correct · 13\/20/);
  assert.match(await row(pending.prompt).innerText(),/Not yet graded/);
  assert.match(await row(viewed.prompt).innerText(),/No answers yet/);
  assert.match(await row(unseen.prompt).innerText(),/Not seen/);
  console.log('PASS explorer distinguishes seen, unseen, ungraded, and exact accuracy');
  await form.locator('[name=history]').selectOption('unseen');
  await form.locator('#browse-summary').filter({hasText:'1 matching question'}).waitFor();
  await form.locator('[name=count]').fill('2');
  await form.locator('#preview-sets').click();
  await form.locator('.selection-issue').waitFor();
  assert.equal(await form.locator('#assign-preview').isDisabled(),true);
  assert.equal(store.assignments().length,0);
  await form.locator('[name=count]').fill('1');
  await form.locator('#preview-sets').click();
  await form.locator('#assign-preview:not(:disabled)').waitFor();
  assert.match(await form.locator('#assignment-preview').innerText(),new RegExp(unseen.prompt.replace('+','\\+')));
  console.log('PASS unseen count selection and shortages block creation');
  await form.locator('[name=history]').selectOption('all');
  assert.equal(await form.locator('#assign-preview').isDisabled(),true);
  await form.locator('[name=accuracyBelow]').fill('65');
  await form.locator('[name=minAttempts]').fill('2');
  await form.locator('[name=allMatching]').check();
  await form.locator('#preview-sets').click();
  await form.locator('#assign-preview:not(:disabled)').waitFor();
  assert.equal(await form.locator('#assignment-preview .assignment-question').count(),1);
  assert.match(await form.locator('#assignment-preview').innerText(),/Find two plus two/);
  await page.screenshot({path:'test-results/assignment-builder.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'test-results/assignment-builder-mobile.png',fullPage:true});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  assert.equal(await form.evaluate(el=>el.scrollWidth<=el.clientWidth+1),true);
  console.log('PASS accuracy below 65 excludes exactly 65 and ungraded; mobile fits');
  await page.setViewportSize({width:1440,height:1100});
  await form.locator('[name=minAttempts]').fill('1');
  await form.locator('[name=students][value=sam]').check();
  await form.locator('#preview-sets').click();
  await form.locator('#assign-preview:not(:disabled)').waitFor();
  assert.equal(await form.locator('#assignment-preview .student-set').count(),2);
  await form.locator('#assign-preview').click();
  await page.locator('#modal').waitFor({state:'hidden'});
  assert.deepEqual(store.assignments('alex')[0].questions.map(q=>q.id),[weak.id]);
  assert.deepEqual(store.assignments('sam')[0].questions.map(q=>q.id),[boundary.id]);
  console.log('PASS multi-student assignments use each learner’s own performance');
  await page.getByRole('button',{name:'Create assignment',exact:true}).first().click();
  await form.locator('[name=students][value=alex]').check();
  await form.locator('[name=mode][value=manual]').check();
  await form.locator('[name=browseSearch]').fill('Find two plus two');
  await form.locator('#browse-summary').filter({hasText:'1 matching question'}).waitFor();
  await form.getByRole('button',{name:'Select all matching',exact:true}).click();
  assert.equal(await form.locator('[name=manualQuestion]:checked').count(),1);
  await form.locator('#preview-sets').click();
  await form.locator('#assign-preview:not(:disabled)').waitFor();
  await form.locator('[name=title]').fill('Try again');
  await form.locator('#assign-preview').click();
  await page.locator('#modal').waitFor({state:'hidden'});
  assert.equal(store.assignments('alex').length,2);
  assert.deepEqual(errors,[]);
  console.log('PASS optional manual filtered selection and reassignment; no browser errors');
} catch(error) {
  await page.screenshot({path:'test-results/assignment-failure.png',fullPage:true}).catch(()=>{});
  throw error;
} finally {await browser.close();server.close();store.db.close();}

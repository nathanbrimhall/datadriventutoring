import { chromium } from 'playwright';
import { createApp } from '../server.mjs';
import { mkdirSync } from 'node:fs';
import assert from 'node:assert/strict';

mkdirSync('test-results',{recursive:true});
const {server,store}=createApp({dataDir:':memory:'});
await new Promise(r=>server.listen(0,'127.0.0.1',r));
const base='http://localhost:'+server.address().port;
const browser=await chromium.launch({headless:true,...(process.env.BROWSER_CHANNEL?{channel:process.env.BROWSER_CHANNEL}:{})});
const failures=[];
try {
  const tutor=await browser.newPage({viewport:{width:1440,height:1000}});
  tutor.on('pageerror',error=>failures.push(error.message));
  await tutor.goto(base+'/#access='+store.bootstrapToken);
  await tutor.getByRole('heading',{name:'Good things start with understanding.'}).waitFor();
  await tutor.screenshot({path:'test-results/tutor-overview.png',fullPage:true});
  await tutor.locator('nav a[href="#students"]').click();
  await tutor.getByRole('button',{name:'Add student'}).first().click();
  await tutor.locator('#student-form input[name="name"]').fill('Alex');
  await tutor.getByRole('button',{name:'Create private links'}).click();
  await tutor.locator('input[aria-label="studentLink"]').waitFor();
  const studentLink=await tutor.locator('input[aria-label="studentLink"]').inputValue();
  const parentLink=await tutor.locator('input[aria-label="parentLink"]').inputValue();
  await tutor.getByRole('button',{name:'Done',exact:true}).click();
  console.log('PASS tutor creates first-name-only student and separate parent link');
  await tutor.locator('nav a[href="#questions"]').click();
  await tutor.getByRole('button',{name:'Add question',exact:true}).click();
  await tutor.locator('#question-form textarea[name="prompt"]').fill('Evaluate 2 to the third power.');
  await tutor.locator('#question-form input[name="topics"]').fill('Exponents');
  await tutor.locator('#question-form input[name="courses"]').fill('Algebra I, GED');
  await tutor.locator('#question-form select[name="type"]').selectOption('short-response');
  await tutor.locator('#question-form textarea[name="answer"]').fill('8');
  await tutor.locator('#question-form textarea[name="explanation"]').fill('2 × 2 × 2 = 8.');
  await tutor.getByRole('button',{name:'Add to question bank'}).click();
  await tutor.locator('#modal').waitFor({state:'hidden'});
  await tutor.locator('.question-row').filter({hasText:'Evaluate 2 to the third power.'}).locator('input').check();
  await tutor.getByRole('button',{name:/Assign selected/}).click();
  await tutor.locator('#assignment-builder-form input[name="title"]').fill('A little exponent practice');
  await tutor.locator('#assignment-builder-form input[name="students"]').check();
  await tutor.getByRole('button',{name:'Preview question sets'}).click();
  await tutor.locator('#assign-preview:not(:disabled)').waitFor();
  await tutor.getByRole('button',{name:'Assign question set',exact:true}).click();
  await tutor.locator('#modal').waitFor({state:'hidden'});
  await tutor.getByRole('heading',{name:'A little exponent practice'}).waitFor();
  console.log('PASS author question and assign selected set');

  const student=await browser.newPage({viewport:{width:1365,height:950}});
  student.on('pageerror',error=>failures.push(error.message));
  await student.goto(studentLink);
  await student.getByRole('heading',{name:'Small steps. Real progress.'}).waitFor();
  await student.getByRole('button',{name:/Continue practice/}).click();
  await student.locator('math-field').waitFor();
  await student.locator('math-field').click();
  await student.keyboard.type('2^3',{delay:70});
  assert.match(await student.locator('math-field').evaluate(el=>el.value),/2\^/);
  await student.screenshot({path:'test-results/math-practice.png',fullPage:true});
  await student.getByRole('button',{name:/Check answer/}).click();
  await student.getByRole('heading',{name:'That’s right. Nicely done.'}).waitFor();
  await student.getByRole('button',{name:/Next question/}).click();
  await student.getByText('Assignment complete. Your progress has been saved.').waitFor();
  console.log('PASS formatted exponent input, equivalent grading, assignment completion');

  await student.locator('#practice-filters select[name="topic"]').selectOption('Probability');
  await student.getByRole('button',{name:/Let’s practice/}).click();
  await student.locator('math-field').waitFor();
  await student.getByRole('button',{name:'Square root',exact:true}).click();
  assert.match(await student.locator('math-field').evaluate(el=>el.value),/\\sqrt/);
  await student.locator('math-field').evaluate(el=>{el.value='';el.focus();});
  await student.keyboard.type('sqrt',{delay:80});
  assert.match(await student.locator('math-field').evaluate(el=>el.value),/sqrt/);
  await student.locator('math-field').evaluate(el=>{el.value='';el.focus();});
  await student.getByRole('button',{name:'Fraction',exact:true}).click();
  assert.match(await student.locator('math-field').evaluate(el=>el.value),/frac/);
  await student.getByRole('button',{name:'⌨ Keyboard',exact:true}).click();
  assert.equal(await student.evaluate(()=>window.mathVirtualKeyboard.visible),true);
  await student.evaluate(()=>window.mathVirtualKeyboard.hide());
  console.log('PASS sqrt shortcut, clickable roots/fractions, full virtual keyboard');
  for(let i=0;i<5;i++) {
    await student.getByRole('heading',{name:'Take your time. You’ve got this.'}).click();
    await student.locator('math-field').evaluate(el=>{el.value='';});
    await student.locator('math-field').click();
    await student.keyboard.type('2^3',{delay:10});
    assert.equal(await student.locator('math-field').evaluate(el=>el.value),'2^3');
  }
  console.log('PASS fast first-character entry across five focus changes');
  await student.locator('math-field').evaluate(el=>{el.value='\\frac{3}{8}';});
  await student.setViewportSize({width:390,height:844});
  await student.screenshot({path:'test-results/mobile-math.png',fullPage:true});
  assert.equal(await student.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true);
  console.log('PASS mobile layout has no horizontal overflow');

  const parent=await browser.newPage({viewport:{width:1440,height:1000}});
  parent.on('pageerror',error=>failures.push(error.message));
  await parent.goto(parentLink);
  await parent.getByText('Parent · read only',{exact:true}).waitFor();
  assert.equal(await parent.locator('nav a[href="#practice"]').count(),0);
  await parent.locator('nav a[href="#analytics"]').click();
  await parent.getByRole('heading',{name:'Progress, with perspective.'}).waitFor();
  await parent.getByText('100%',{exact:true}).first().waitFor();
  await parent.screenshot({path:'test-results/parent-progress.png',fullPage:true});
  console.log('PASS parent sees child results without practice controls');

  await tutor.locator('nav a[href="#settings"]').click();
  await tutor.locator('input[name="name"]').fill('ProgressPoint');
  await tutor.getByRole('button',{name:/Save settings/}).click();
  await tutor.getByText('Workspace settings saved.').waitFor();
  await tutor.locator('nav a[href="#analytics"]').click();
  await tutor.getByRole('heading',{name:'Progress, with perspective.'}).waitFor();
  await tutor.screenshot({path:'test-results/tutor-analytics.png',fullPage:true});
  await tutor.locator('nav a[href="#about"]').click();
  await tutor.getByRole('heading',{name:'Every learner has a next step.'}).waitFor();
  console.log('PASS settings, analytics, and about navigation');
  assert.deepEqual(failures,[]);
  console.log('PASS no uncaught browser errors');
} catch(error) {
  console.log('Browser errors:', failures);
  for(const [i,context]of browser.contexts().entries()) for(const page of context.pages())await page.screenshot({path:'test-results/failure-'+i+'.png',fullPage:true}).catch(()=>{});
  throw error;
} finally {await browser.close();server.close();store.db.close();}
